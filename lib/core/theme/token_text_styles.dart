  static TextStyle _make({
    Color? color,
    FontWeight? weight,
    FontWeight? fontWeight,
    double? fontSize,
    double? letterSpacing,
    double? height,
    double? wordSpacing,
    FontStyle? fontStyle,
    TextDecoration? decoration,
    Color? decorationColor,
    TextDecorationStyle? decorationStyle,
    double? decorationThickness,
    List<Shadow>? shadows,
    String? fontFamily,
    Paint? foreground,
    Paint? background,
    TextBaseline? textBaseline,
    TextLeadingDistribution? leadingDistribution,
    Locale? locale,
    List<FontFeature>? fontFeatures,
    required double baseSize,
    required FontWeight baseWeight,
    required String baseFamily,
    double? baseLetterSpacing,
    double? baseHeight,
  }) {
    return TextStyle(
      fontSize: fontSize ?? baseSize,
      fontWeight: weight ?? fontWeight ?? baseWeight,
      fontFamily: fontFamily ?? baseFamily,
      color: color,
      letterSpacing: letterSpacing ?? baseLetterSpacing,
      height: height ?? baseHeight,
      wordSpacing: wordSpacing,
      fontStyle: fontStyle,
      decoration: decoration,
      decorationColor: decorationColor,
      decorationStyle: decorationStyle,
      decorationThickness: decorationThickness,
      shadows: shadows,
      foreground: foreground,
      background: background,
      textBaseline: textBaseline,
      leadingDistribution: leadingDistribution,
      locale: locale,
      fontFeatures: fontFeatures,
    );
  }


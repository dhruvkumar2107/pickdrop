/// PickDrop typography tokens.
///
/// Every member is a static method that returns a [TextStyle]. It accepts an
/// optional [color] and [weight] (plus common TextStyle overrides), so it can be
/// used as `TokenTextStyles.titleMedium()` or
/// `TokenTextStyles.titleMedium(color: c, weight: w)`.
